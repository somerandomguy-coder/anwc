// Records the studio's built-in examples from the real example apps, so the
// overlay always matches the page. Start the apps on 4175/4176/4177 and build
// first, then run: node scripts/record-studio-captures.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const cli = join(root, 'packages/cli/src/main.ts');
const examples = [
  { id: 'shop-blocked-checkout', title: 'Shop: checkout covered', description: 'A cookie notice covers the checkout button.', url: 'http://127.0.0.1:4175/lab?case=blocked-checkout' },
  { id: 'clean-shop', title: 'Shop: checkout reachable', description: 'The healthy control for the covered checkout.', url: 'http://127.0.0.1:4175/lab?case=blocked-checkout&variant=healthy' },
  { id: 'pricing-text-clip', title: 'Pricing: description cut off', description: 'A plan description is cut off by its own box.', url: 'http://127.0.0.1:4176/?case=description-crop&variant=broken' },
  { id: 'dashboard-outside-viewport', title: 'Dashboard: save off screen', description: 'The save button sits outside the mobile viewport.', url: 'http://127.0.0.1:4177/?case=outside-save&variant=broken' }
];
const dir = mkdtempSync(join(tmpdir(), 'anwc-captures-'));
const recorded = examples.map((example) => {
  const file = join(dir, `${example.id}.json`);
  execFileSync(process.execPath, ['--import', 'tsx', cli, 'inspect', example.url, '--viewport', '390x844', '--format', 'json', '--output', file], { cwd: root, stdio: 'inherit' });
  const { url, ...rest } = example;
  return { ...rest, snapshot: JSON.parse(readFileSync(file, 'utf8')) };
});
const body = recorded.map((r) => `  ${JSON.stringify(r)}`).join(',\n');
const out = `// Generated by scripts/record-studio-captures.mjs. Do not edit.\n// Real captures of the example apps, recorded ${recorded[0].snapshot.capturedAt.slice(0, 10)}.\nexport const RECORDED_EXAMPLES: unknown[] = [\n${body}\n];\n`;
for (const target of ['packages/studio/src/data/recorded.ts', 'packages/cli/src/studio-recorded.ts']) writeFileSync(join(root, target), out);
console.log(`Recorded ${recorded.length} captures.`);
